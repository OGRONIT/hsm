// ─────────────────────────────────────────────────────────────
// HSM Messaging — Resend Email Client
// Sends outreach and followup emails on behalf of Smit
// From: smit@hariii.design (must be verified in Resend)
// ─────────────────────────────────────────────────────────────

import { Resend } from 'resend';
import { createClient } from '@supabase/supabase-js';

const resendApiKey = process.env.RESEND_API_KEY?.trim() || '';
const resend = resendApiKey ? new Resend(resendApiKey) : null;
const supabase = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL?.trim() || 'https://placeholder.supabase.co',
  process.env.SUPABASE_SERVICE_ROLE_KEY?.trim() || 'placeholder-service-role-key',
);

const FROM_EMAIL = 'Smit Barbhaya <smit@hariii.design>';
const REPLY_TO   = 'smit@hariii.design';

// ─────────────────────────────────────────────────────────────
// Send outreach email
// ─────────────────────────────────────────────────────────────
export interface OutreachEmailInput {
  to:          string;
  toName:      string;
  companyName: string;
  industry:    string;
  bodyText:    string;   // Generated by bot (plain text from GPT)
}

export async function sendOutreachEmail(input: OutreachEmailInput): Promise<{
  success: boolean; emailId: string | null; error?: string;
}> {
  const subject = buildOutreachSubject(input.companyName, input.industry);

  if (!resend) {
    return { success: false, emailId: null, error: 'RESEND_API_KEY not configured' };
  }

  try {
    const { data, error } = await resend.emails.send({
      from:     FROM_EMAIL,
      to:       [`${input.toName} <${input.to}>`],
      reply_to: REPLY_TO,
      subject,
      html:     buildOutreachHtml(input.bodyText, input.toName),
      text:     input.bodyText,   // Plain text fallback
      tags: [
        { name: 'type',     value: 'outreach' },
        { name: 'industry', value: input.industry },
      ],
    });

    if (error) {
      console.error('[Resend] Send failed:', error.message);
      return { success: false, emailId: null, error: error.message };
    }

    console.log(`[Resend] ✓ Outreach sent to ${input.to} | emailId: ${data?.id}`);
    return { success: true, emailId: data?.id ?? null };

  } catch (err: any) {
    console.error('[Resend] Network error:', err.message);
    return { success: false, emailId: null, error: err.message };
  }
}

// ─────────────────────────────────────────────────────────────
// Send followup email
// ─────────────────────────────────────────────────────────────
export async function sendFollowupEmail(input: {
  to:             string;
  toName:         string;
  companyName:    string;
  bodyText:       string;
  followupNumber: 1 | 2;
}): Promise<{ success: boolean; emailId: string | null; error?: string }> {
  if (!resend) {
    return { success: false, emailId: null, error: 'RESEND_API_KEY not configured' };
  }

  try {
    const { data, error } = await resend.emails.send({
      from:    FROM_EMAIL,
      to:      [`${input.toName} <${input.to}>`],
      reply_to: REPLY_TO,
      subject: `Following up — Hariii Design × ${input.companyName}`,
      html:    buildFollowupHtml(input.bodyText, input.toName),
      text:    input.bodyText,
      tags: [
        { name: 'type',   value: 'followup' },
        { name: 'number', value: String(input.followupNumber) },
      ],
    });

    if (error) return { success: false, emailId: null, error: error.message };
    return { success: true, emailId: data?.id ?? null };
  } catch (err: any) {
    return { success: false, emailId: null, error: err.message };
  }
}

// ─────────────────────────────────────────────────────────────
// Health check — used by admin panel "Test Key" button
// ─────────────────────────────────────────────────────────────
export async function testResendConnection(): Promise<{ ok: boolean; error?: string }> {
  if (!resendApiKey) return { ok: false, error: 'RESEND_API_KEY not set' };

  try {
    // Resend has no explicit ping — check domains list as proxy
    const res = await fetch('https://api.resend.com/domains', {
      headers: { 'Authorization': `Bearer ${resendApiKey}` },
    });
    return { ok: res.ok };
  } catch (err: any) {
    return { ok: false, error: err.message };
  }
}

// ─────────────────────────────────────────────────────────────
// Email HTML templates — clean, minimal, mobile-friendly
// Designed to look like a real personal email, not a newsletter
// ─────────────────────────────────────────────────────────────
function buildOutreachSubject(company: string, industry: string): string {
  const hooks: Record<string, string> = {
    home_appliances:   `3D animations for ${company}'s product line`,
    heavy_machinery:   `3D visualization for ${company} — worth a look?`,
    safes:             `Showcase ${company}'s security products in 3D`,
    submersible_pumps: `3D cross-sections for ${company}'s pump range`,
    peanut_sorting:    `3D animations for ${company}'s sorting machines`,
    auto_parts:        `3D renders for ${company}'s parts catalog`,
    other:             `A quick idea for ${company}`,
  };
  return hooks[industry] ?? hooks.other;
}

